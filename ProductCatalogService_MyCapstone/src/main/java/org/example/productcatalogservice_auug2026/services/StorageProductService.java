package org.example.productcatalogservice_auug2026.services;

import org.example.productcatalogservice_auug2026.dtos.UserDto;
import org.example.productcatalogservice_auug2026.models.Category;
import org.example.productcatalogservice_auug2026.models.Product;
import org.example.productcatalogservice_auug2026.repos.CategoryRepo;
import org.example.productcatalogservice_auug2026.repos.ProductRepo;
import org.example.productcatalogservice_auug2026.search.IProductSearchIndexer;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Primary;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Sort;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;

import java.util.Date;
import java.util.Optional;

@Service
@Primary
public class StorageProductService implements IProductService {

    @Autowired
    private ProductRepo productRepo;

    @Autowired
    private CategoryRepo categoryRepo;

    @Autowired
    private IProductSearchIndexer productSearchIndexer;

    @Autowired
    private RestTemplate restTemplate;

    @Override
    public Product getProductDetailsById(Long id) {
        Optional<Product> productOptional = productRepo.findById(id);
        if(productOptional.isPresent()) {
            return productOptional.get();
        }

        return null;
    }

    @Override
    public Product replaceProduct(Long id, Product inputProduct) {
        Optional<Product> productOptional = productRepo.findById(id);
        if (productOptional.isEmpty()) {
            throw new RuntimeException("Product with id "+id+" doesn't exists");
        }

        inputProduct.setId(id);
        inputProduct.setCreatedAt(productOptional.get().getCreatedAt());
        inputProduct.setLastUpdatedAt(new Date());
        inputProduct.setCategory(resolveCategory(inputProduct.getCategory()));
        Product saved = productRepo.save(inputProduct);
        productSearchIndexer.index(saved);
        return saved;
    }

    @Override
    public Product createProduct(Product product) {
        if (product.getName() == null || product.getName().isBlank()) {
            throw new IllegalArgumentException("Product name is required");
        }
        if (product.getPrice() == null || product.getPrice() < 0) {
            throw new IllegalArgumentException("Product price must be >= 0");
        }
        // ids are generated by the database
        product.setId(null);
        product.setCategory(resolveCategory(product.getCategory()));
        Product saved = productRepo.save(product);
        productSearchIndexer.index(saved);
        return saved;
    }

    @Override
    public Product getProductBasedOnUserRole(Long productId, Long userId) {
        Optional<Product> productOptional = productRepo.findById(productId);
        if(productOptional.isEmpty()) return null;

        // we are calling user service using SD
        ResponseEntity<UserDto> userDtoResponseEntity =
                restTemplate.getForEntity("http://userservice/users/{userId}", UserDto.class, userId);


        //This conditions tests that response is not null
        if(userDtoResponseEntity.hasBody()) {
            System.out.println(userDtoResponseEntity.getBody().getEmail());
            return productOptional.get();
        }

        return null;
    }

    @Override
    public Page<Product> getAllProducts(Integer pageNumber, Integer pageSize) {
        return productRepo.findAll(PageRequest.of(pageNumber, pageSize, Sort.by("id")));
    }

    @Override
    public Page<Product> getProductsByCategory(Long categoryId, Integer pageNumber, Integer pageSize) {
        if (!categoryRepo.existsById(categoryId)) {
            throw new RuntimeException("Category with id " + categoryId + " doesn't exists");
        }
        return productRepo.findByCategory_Id(categoryId, PageRequest.of(pageNumber, pageSize, Sort.by("id")));
    }

    @Override
    public void deleteProduct(Long id) {
        if (!productRepo.existsById(id)) {
            throw new RuntimeException("Product with id "+id+" doesn't exists");
        }
        productRepo.deleteById(id);
        productSearchIndexer.remove(id);
    }

    // Links a product to an existing category (by id, else by name), creating the category if it is new.
    private Category resolveCategory(Category category) {
        if (category == null) return null;
        if (category.getId() != null) {
            Optional<Category> byId = categoryRepo.findById(category.getId());
            if (byId.isPresent()) return byId.get();
        }
        if (category.getName() == null || category.getName().isBlank()) {
            throw new IllegalArgumentException("Category must have a valid id or a name");
        }
        Optional<Category> byName = categoryRepo.findByNameIgnoreCase(category.getName());
        if (byName.isPresent()) return byName.get();

        Category newCategory = new Category();
        newCategory.setName(category.getName());
        newCategory.setDescription(category.getDescription());
        return categoryRepo.save(newCategory);
    }
}
